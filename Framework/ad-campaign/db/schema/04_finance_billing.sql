-- Module: finance.billing
-- Append-only financial ledger for wins and manual corrections. Idempotent
-- on (tenant_id, source_event_id) — see finance.billing.BillingService.
-- Plain tenant_id/campaign_id (no FK): billing is deliberately decoupled
-- from campaign's schema.

CREATE TABLE ledger_entries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       bigint NOT NULL,
    campaign_id     bigint,
    entry_type      varchar(255) NOT NULL,
    source_event_id varchar(255) NOT NULL,
    media_cost      numeric(14,4),
    platform_fee    numeric(14,4),
    total_amount    numeric(14,4) NOT NULL,
    currency        varchar(255) NOT NULL,
    created_by      bigint,
    created_at      timestamp(6),
    CONSTRAINT uk_ledger_entry_source_event UNIQUE (tenant_id, source_event_id),
    CONSTRAINT chk_ledger_entries_entry_type CHECK (entry_type IN ('CHARGE', 'ADJUSTMENT'))
);
