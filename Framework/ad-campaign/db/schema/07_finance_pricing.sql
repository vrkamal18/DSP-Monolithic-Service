-- Module: finance.pricing
-- One platform-fee percentage per tenant (fraction, e.g. 0.08 = 8%). No row
-- for a tenant means the application-level default percentage applies
-- (see finance.pricing.FeeCalculationService) — there is no global/
-- default-tenant row at the DB level.

CREATE TABLE tenant_fee_configs (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            bigint NOT NULL,
    platform_fee_percent numeric(6,4) NOT NULL,
    CONSTRAINT fk_tenant_fee_configs_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT uk_tenant_fee_config_tenant UNIQUE (tenant_id)
);
