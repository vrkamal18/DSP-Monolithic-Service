-- Module: measurement
-- Public tracking-pixel events (impression/click/conversion/viewability/
-- video quartile). tenant_id/campaign_id/creative_id are trusted opaque
-- identifiers only — measurement never depends on campaign's schema (see
-- service/documents/01-service-architecture.md §6: "measurement -> foundation
-- event contract" — no campaign/creative dependency at all). Idempotent on
-- (tenant_id, event_id).

CREATE TABLE measurement_events (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             bigint NOT NULL,
    campaign_id           bigint NOT NULL,
    creative_id           bigint,
    event_type            varchar(255) NOT NULL,
    event_id              varchar(255) NOT NULL,
    destination_url       varchar(255),
    conversion_type       varchar(255),
    conversion_value      numeric(12,4),
    viewable_duration_ms  integer,
    viewable_percentage   integer,
    video_quartile        varchar(255),
    recorded_at           timestamp(6),
    CONSTRAINT uk_measurement_event_tenant_event UNIQUE (tenant_id, event_id),
    CONSTRAINT chk_measurement_events_type CHECK (event_type IN
        ('IMPRESSION', 'CLICK', 'CONVERSION', 'VIEWABILITY', 'VIDEO_QUARTILE')),
    CONSTRAINT chk_measurement_events_quartile CHECK (video_quartile IS NULL OR video_quartile IN
        ('START', 'FIRST_QUARTILE', 'MIDPOINT', 'THIRD_QUARTILE', 'COMPLETE'))
);
