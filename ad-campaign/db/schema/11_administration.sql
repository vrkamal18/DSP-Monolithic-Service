-- Module: administration
-- Append-only audit record for administrative actions (actor, tenant,
-- action, target, time, correlation id) per
-- service/documents/03-domain-and-data-specification.md §8. No update/
-- delete anywhere in the application — protected from tenant modification
-- by construction.

CREATE TABLE admin_audit_logs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id    bigint NOT NULL,
    actor_tenant_id  bigint NOT NULL,
    target_tenant_id bigint,
    target_user_id   bigint,
    action           varchar(255) NOT NULL,
    details          varchar(255),
    correlation_id   varchar(255),
    created_at       timestamp(6),
    CONSTRAINT chk_admin_audit_logs_action CHECK (action IN (
        'USER_CREATED', 'USER_ROLE_GRANTED', 'USER_ROLE_REVOKED', 'USER_DEACTIVATED',
        'USER_REACTIVATED', 'TENANT_DEACTIVATED', 'TENANT_REACTIVATED'
    ))
);
