-- Module: connectors
-- External platform connections (social/DMP/OTT), their activity/sync audit
-- log, and campaign-to-external-id mappings. Plain tenant_id/campaign_id
-- (no FK) throughout.

CREATE TABLE connectors (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            bigint NOT NULL,
    type                 varchar(255) NOT NULL,
    status               varchar(255) NOT NULL,
    external_account_id  varchar(255),
    -- Opaque credential reference, accepted on write, never returned in any
    -- response DTO — see connectors.entity.Connector's javadoc.
    credential_ref       varchar(255),
    connected_at         timestamp(6),
    last_synced_at       timestamp(6),
    last_tested_at       timestamp(6),
    last_test_successful boolean,
    CONSTRAINT uk_connector_tenant_type UNIQUE (tenant_id, type),
    CONSTRAINT chk_connectors_type CHECK (type IN ('SOCIAL', 'DMP', 'OTT')),
    CONSTRAINT chk_connectors_status CHECK (status IN ('DISCONNECTED', 'CONNECTED', 'ERROR'))
);

-- Generic activity/history log covering every connector action (connect,
-- disconnect, test, sync, push/pause/resume campaign) rather than one
-- table per action type.
CREATE TABLE connector_activities (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint NOT NULL,
    connector_id  bigint NOT NULL,
    activity_type varchar(255) NOT NULL,
    success       boolean NOT NULL,
    details       varchar(255),
    created_at    timestamp(6),
    CONSTRAINT chk_connector_activities_type CHECK (activity_type IN
        ('CONNECT', 'DISCONNECT', 'TEST', 'SYNC', 'PUSH_CAMPAIGN', 'PAUSE_CAMPAIGN', 'RESUME_CAMPAIGN'))
);

CREATE TABLE external_id_mappings (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             bigint NOT NULL,
    connector_id          bigint NOT NULL,
    campaign_id           bigint NOT NULL,
    external_campaign_id  varchar(255) NOT NULL,
    CONSTRAINT uk_external_id_mapping UNIQUE (tenant_id, connector_id, campaign_id)
);
