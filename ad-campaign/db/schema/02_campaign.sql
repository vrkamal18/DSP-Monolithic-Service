-- Module: campaign
-- Advertiser, campaign, budget/pacing, creative, targeting, and the legacy
-- ad_impressions/ad_clicks audit tables are all owned by this module today
-- (advertiser/creative/audience are not yet split into their own top-level
-- packages — see the module-parity notes in service/documents).

CREATE TABLE advertisers (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  bigint NOT NULL,
    name       varchar(255) NOT NULL,
    email      varchar(255),
    company    varchar(255),
    created_at timestamp(6),
    CONSTRAINT fk_advertisers_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id)
);

CREATE TABLE campaigns (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint NOT NULL,
    advertiser_id bigint,
    name          varchar(255) NOT NULL,
    bid_price     numeric(12,4),
    objective     varchar(255),
    start_date    timestamp(6),
    end_date      timestamp(6),
    status        varchar(255) NOT NULL,
    created_at    timestamp(6),
    CONSTRAINT fk_campaigns_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_campaigns_advertiser FOREIGN KEY (advertiser_id) REFERENCES advertisers (id),
    CONSTRAINT chk_campaigns_status CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'COMPLETED', 'ARCHIVED'))
);

CREATE TABLE budgets (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint NOT NULL,
    campaign_id   bigint,
    total_budget  numeric(14,4) NOT NULL,
    daily_cap     numeric(14,4),
    spent_amount  numeric(14,4),
    pacing_mode   varchar(255),
    CONSTRAINT fk_budgets_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_budgets_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT uk_budget_campaign UNIQUE (campaign_id)
);

-- Per-day spend used by bidding.PacingService for daily-cap enforcement.
-- Plain campaign_id (no FK) — an internal pacing fact table, not
-- cross-referenced by anything outside bidding.
CREATE TABLE budget_daily_spend (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  bigint NOT NULL,
    spend_date   date NOT NULL,
    spent_amount numeric(14,4) NOT NULL,
    CONSTRAINT uk_budget_daily_spend UNIQUE (campaign_id, spend_date)
);

CREATE TABLE creatives (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           bigint NOT NULL,
    campaign_id         bigint,
    name                varchar(255),
    creative_type       varchar(255),
    url                 varchar(255),
    width               integer,
    height              integer,
    status              varchar(255) NOT NULL,
    rejection_reason    varchar(255),
    reviewed_by_user_id bigint,
    reviewed_at         timestamp(6),
    created_at          timestamp(6),
    CONSTRAINT fk_creatives_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_creatives_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT chk_creatives_status CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED', 'ARCHIVED'))
);

-- Flat include/exclude targeting conditions (location/device). This is the
-- full extent of "Audience" today — no segment/DMP-style audience module
-- exists yet.
CREATE TABLE targeting_rules (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint NOT NULL,
    campaign_id    bigint,
    rule_type      varchar(255),
    condition_type varchar(255),
    rule_value     varchar(255),
    CONSTRAINT fk_targeting_rules_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_targeting_rules_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id)
);

-- Campaign lifecycle audit trail. Plain ids (no FK), same pattern as every
-- other append-only activity/audit table in this schema.
CREATE TABLE campaign_status_changes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint NOT NULL,
    campaign_id bigint NOT NULL,
    from_status varchar(255),
    to_status   varchar(255) NOT NULL,
    changed_by  bigint,
    changed_at  timestamp(6),
    CONSTRAINT chk_campaign_status_changes_from CHECK (from_status IN
        ('DRAFT', 'ACTIVE', 'PAUSED', 'COMPLETED', 'ARCHIVED')),
    CONSTRAINT chk_campaign_status_changes_to CHECK (to_status IN
        ('DRAFT', 'ACTIVE', 'PAUSED', 'COMPLETED', 'ARCHIVED'))
);

-- Legacy "bid won" audit records written internally by
-- bidding.BiddingService.decide() — not a real render/click measurement
-- pixel (see measurement_events for that). No tenant_id column at all;
-- pre-dates per-tenant scoping being added everywhere else.
CREATE TABLE ad_impressions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint,
    creative_id bigint,
    device_type varchar(255),
    location    varchar(255),
    age_group   varchar(255),
    user_id     varchar(255),
    served_at   timestamp(6),
    CONSTRAINT fk_ad_impressions_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT fk_ad_impressions_creative FOREIGN KEY (creative_id) REFERENCES creatives (id)
);

-- Legacy, now-superseded click log behind the unauthenticated /api/clicks
-- endpoint — kept for backward compatibility; real click tracking is
-- measurement_events (event_type = 'CLICK') via /t/click.
CREATE TABLE ad_clicks (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint,
    creative_id bigint,
    user_id     varchar(255),
    location    varchar(255),
    device_type varchar(255),
    clicked_at  timestamp(6),
    CONSTRAINT fk_ad_clicks_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT fk_ad_clicks_creative FOREIGN KEY (creative_id) REFERENCES creatives (id)
);
