-- Module: finance.invoicing
-- Generated from finance.billing's ledger_entries for a billing period.
-- PDF rendering (Apache PDFBox) and email delivery (mock adapter) are
-- application-layer concerns, not reflected in this schema.

CREATE TABLE invoices (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint NOT NULL,
    advertiser_id bigint NOT NULL,
    period_start  date NOT NULL,
    period_end    date NOT NULL,
    total_amount  numeric(14,4) NOT NULL,
    currency      varchar(255) NOT NULL,
    status        varchar(255) NOT NULL,
    created_at    timestamp(6),
    issued_at     timestamp(6),
    sent_at       timestamp(6),
    paid_at       timestamp(6),
    voided_at     timestamp(6),
    CONSTRAINT uk_invoice_tenant_advertiser_period UNIQUE (tenant_id, advertiser_id, period_start, period_end),
    CONSTRAINT chk_invoices_status CHECK (status IN ('DRAFT', 'ISSUED', 'SENT', 'PAID', 'VOID'))
);

CREATE TABLE invoice_line_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  bigint NOT NULL,
    campaign_id bigint,
    description varchar(255) NOT NULL,
    amount      numeric(14,4) NOT NULL
);
