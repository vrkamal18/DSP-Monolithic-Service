-- Module: channels
-- Per-tenant enablement of ad-format channel types, and which campaigns are
-- assigned to which channel. Plain tenant_id/campaign_id (no FK) — channels
-- depends on campaign's contracts, not its schema directly.

CREATE TABLE channels (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    type      varchar(255) NOT NULL,
    enabled   boolean NOT NULL,
    CONSTRAINT uk_channel_tenant_type UNIQUE (tenant_id, type),
    CONSTRAINT chk_channels_type CHECK (type IN
        ('DISPLAY', 'NATIVE', 'VIDEO', 'AUDIO', 'OTT_CTV', 'DOOH', 'SOCIAL'))
);

CREATE TABLE campaign_channels (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint NOT NULL,
    campaign_id  bigint NOT NULL,
    channel_type varchar(255) NOT NULL,
    CONSTRAINT uk_campaign_channel UNIQUE (tenant_id, campaign_id, channel_type),
    CONSTRAINT chk_campaign_channels_type CHECK (channel_type IN
        ('DISPLAY', 'NATIVE', 'VIDEO', 'AUDIO', 'OTT_CTV', 'DOOH', 'SOCIAL'))
);
