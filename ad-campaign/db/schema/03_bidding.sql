-- Module: bidding
-- Diagnostic/decision log and frequency-cap counters. Plain ids throughout
-- (no FKs) — this is the hot, tmax-bounded decisioning path, deliberately
-- decoupled from other modules' schemas.

CREATE TABLE bid_decision_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid_request_id varchar(255) NOT NULL,
    campaign_id    bigint,
    exchange       varchar(255) NOT NULL,
    outcome        varchar(255) NOT NULL,
    reason_code    varchar(255),
    price          numeric(12,4),
    created_at     timestamp(6)
);

CREATE TABLE frequency_cap_entries (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      bigint NOT NULL,
    user_id          varchar(255) NOT NULL,
    cap_date         date NOT NULL,
    impression_count integer NOT NULL,
    CONSTRAINT uk_frequency_cap_entry UNIQUE (campaign_id, user_id, cap_date)
);
