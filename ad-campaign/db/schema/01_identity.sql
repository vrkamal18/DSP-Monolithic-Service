-- Module: identity
-- Tenants, users, and role assignments. PLATFORM_ADMIN/SERVICE_PRINCIPAL
-- roles are not tenant-scoped (user_role_assignments.tenant_id is nullable
-- for exactly those two roles).

CREATE TABLE tenants (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(255) NOT NULL,
    -- NULL or true = active; only false means deactivated (see
    -- administration.PlatformAdministrationService.deactivateTenant).
    active     boolean,
    created_at timestamp(6),
    CONSTRAINT uk_tenant_name UNIQUE (name)
);

CREATE TABLE app_users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint NOT NULL,
    email         varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    enabled       boolean NOT NULL,
    created_at    timestamp(6),
    CONSTRAINT fk_app_users_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    -- Same email CAN exist across different tenants; AuthService still
    -- treats email as effectively globally unique at the application layer
    -- via a findByEmailIgnoreCase check before insert.
    CONSTRAINT uk_app_user_tenant_email UNIQUE (tenant_id, email)
);

CREATE TABLE user_role_assignments (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   bigint NOT NULL,
    -- Nullable: a platform-wide role (PLATFORM_ADMIN, SERVICE_PRINCIPAL)
    -- applies regardless of the user's home tenant.
    tenant_id bigint,
    role      varchar(255) NOT NULL,
    CONSTRAINT fk_user_role_assignments_user FOREIGN KEY (user_id) REFERENCES app_users (id),
    CONSTRAINT fk_user_role_assignments_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT chk_user_role_assignments_role CHECK (role IN (
        'PLATFORM_ADMIN', 'TENANT_ADMIN', 'CAMPAIGN_MANAGER', 'CREATIVE_REVIEWER',
        'FINANCE_USER', 'ANALYST', 'SERVICE_PRINCIPAL'
    ))
);
