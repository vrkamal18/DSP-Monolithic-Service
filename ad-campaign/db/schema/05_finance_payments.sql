-- Module: finance.payments
-- Advertiser funding account, saved payment methods, and the append-only
-- transaction ledger behind it (top-ups, refunds, and the AD_SPEND debits
-- bidding.BiddingService/finance.billing.BillingService post on every won,
-- charged impression). Plain tenant_id/advertiser_id throughout (no FK) —
-- see finance.payments.AccountService's own javadoc.

CREATE TABLE accounts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint NOT NULL,
    advertiser_id bigint NOT NULL,
    balance       numeric(14,4) NOT NULL,
    currency      varchar(255) NOT NULL,
    CONSTRAINT uk_account_tenant_advertiser UNIQUE (tenant_id, advertiser_id)
);

CREATE TABLE payment_methods (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint NOT NULL,
    advertiser_id bigint NOT NULL,
    provider      varchar(255) NOT NULL,
    -- Opaque provider token — never a raw card number (no real provider is
    -- wired up yet; see payments.PaymentProviderAdapter / MockPaymentProviderAdapter).
    token         varchar(255) NOT NULL,
    brand         varchar(255),
    last4         varchar(255),
    expiry_month  integer,
    expiry_year   integer,
    created_at    timestamp(6)
);

CREATE TABLE payment_transactions (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          bigint NOT NULL,
    advertiser_id      bigint NOT NULL,
    type               varchar(255) NOT NULL,
    amount             numeric(14,4) NOT NULL,
    currency           varchar(255) NOT NULL,
    source_event_id    varchar(255) NOT NULL,
    provider_charge_id varchar(255),
    created_at         timestamp(6),
    CONSTRAINT uk_transaction_source_event UNIQUE (tenant_id, source_event_id),
    CONSTRAINT chk_payment_transactions_type CHECK (type IN ('TOP_UP', 'REFUND', 'AD_SPEND'))
);
